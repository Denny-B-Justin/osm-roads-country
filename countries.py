# Codes that no longer exist. They are never offered and never listed as "coming soon".
OBSOLETE_CODES = {
    "AN": "Netherlands Antilles, dissolved in 2010",
    "CS": "Serbia and Montenegro, dissolved in 2006",
}

NAMES = dict(COUNTRIES)


def country_name(iso2):
    return NAMES.get(iso2, iso2)


def tracked_codes():
    """Every current code the pipeline covers (obsolete codes removed)."""
    return [iso2 for iso2, _name in COUNTRIES if iso2 not in OBSOLETE_CODES]


def not_yet_available(available_codes):
    """Countries the pipeline covers that have no download yet, sorted by name."""
    available = set(available_codes)
    pending = [iso2 for iso2 in tracked_codes() if iso2 not in available]
    return sorted(pending, key=lambda c: NAMES[c])
